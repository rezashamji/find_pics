"""Golden fixtures for FindPicsCore.PILResize (the phone's port of Pillow's resize(..., BILINEAR), which is the server's
open_clip preprocess for PE-Core-B-16). Inputs are generated by formulas both sides can reproduce (a 64-bit LCG for
noise, an integer pattern for structure); outputs are stored as an FNV-1a 64 hash plus 300 sampled bytes.
Usage (main env): python eval/pil_resize_fixtures.py -> ios/FindPicsCore/Tests/FindPicsCoreTests/Fixtures/pil_resize.json"""
import json

import numpy as np
from PIL import Image

M = (1 << 64) - 1


def make(w, h, kind, seed):
    if kind == "noise":
        s, out = seed, bytearray(w * h * 3)
        for i in range(w * h * 3):
            s = (s * 6364136223846793005 + 1442695040888963407) & M
            out[i] = s >> 56
        return np.frombuffer(bytes(out), np.uint8).reshape(h, w, 3)
    y, x, c = np.mgrid[0:h, 0:w, 0:3]
    return ((x * 3 + y * 5 + c * 71 + (x * y) % 17) & 255).astype(np.uint8)


def fnv(b):
    h = 0xcbf29ce484222325
    for v in b:
        h = ((h ^ v) * 0x100000001b3) & M
    return h


cases = []
for (w, h), (tw, th), kind in [((640, 480), (224, 224), "pattern"), ((480, 640), (224, 224), "noise"),
                               ((1280, 960), (224, 224), "pattern"), ((500, 333), (224, 224), "noise"),
                               ((100, 80), (224, 224), "noise"), ((224, 224), (224, 224), "noise"),
                               ((1600, 1200), (224, 224), "pattern"), ((7, 5), (224, 224), "pattern"),
                               ((1280, 720), (224, 224), "noise"), ((300, 200), (97, 61), "noise"),
                               ((224, 500), (224, 224), "pattern")]:
    seed = w * 1000 + h
    a = make(w, h, kind, seed)
    out = np.asarray(Image.fromarray(a).resize((tw, th), Image.BILINEAR)).tobytes()
    idx = sorted({(i * 7919) % len(out) for i in range(300)})
    cases.append(dict(w=w, h=h, tw=tw, th=th, kind=kind, seed=seed, fnv=str(fnv(out)), idx=idx, vals=[out[i] for i in idx]))
json.dump(cases, open("ios/FindPicsCore/Tests/FindPicsCoreTests/Fixtures/pil_resize.json", "w"))
print("PIL_RESIZE_FIXTURES_OK", len(cases))
